"""语义层「反向索要」守卫（A.58，依据 20 号「零静默」研究设计 · 研究产出 2 的第 3 条）。

问题
----
**反向索要** = 模型把**本应由系统提供**的输入（影像特征 / 病灶边界 / 图像本身）抛回给
医生，让医生复述它才能给出结论。A.37 真机走查实测过这一形态：影像信息（bbox/面积/
切面）没喂进 prompt，thyroid.md 又把成分/回声/形态列为预期输入 → 模型输出
「请提供病灶边界/请描述图像特征」。20 号把它登记为 **P2（3 天）** 的语义层守卫。

与「转人工建议」的区别（**必须区分，否则误伤**）
----------------------------------------------
本专科的**可读降级**文案（A.56）写的是：

    「本例未能解析出 TI-RADS 分级（…），已转人工判读：请结合图像与病史自行分级。」

这里的「请结合图像与病史自行分级」是**转人工后的行动建议**（医生自己判），
不是「向医生索要数据给模型」。两者都用「请」字开头，靠关键词一刀切会误伤 ——
所以本模块的判据是**强动作 + 影像/临床输入对象**：

* 强动作：``请提供`` / ``请描述`` / ``请上传`` / ``请补充`` / ``请复述`` /
  ``麻烦提供`` / ``需要您提供`` / ``请重新提供``；
* 对象（动后 14 字内）：``影像`` / ``图像`` / ``图片`` / ``原图`` / ``切面`` /
  ``声像`` / ``DICOM`` / ``病灶边界`` / ``边界信息`` / ``具体位置`` / ``图像特征`` 等。

``请结合图像与病史…自行判断`` 不含上述强动作 → 天然不命中（用例显式钉住）。
另设 ``is_system_handoff_text`` 兜底：本系统自己写的转人工文案带固定标记
``已转人工判读``（模型不会写这句），即使将来有人把守卫挂到 ``content`` 上，
也不会把系统文案判成模型索要。
"""
from __future__ import annotations

import re

# 系统自己写的转人工文案标记（只出现在本仓库的降级模板里，模型输出不会带）
HANDOFF_MARKER = "已转人工判读"

# 判红后展示给医生的**可读**正文（替换掉含索要的模型原文）
HANDOFF_TEXT = (
    "本例未能基于现有影像与临床信息给出结论（模型把本应由系统提供的影像特征"
    "抛回给了医生），已转人工判读：请结合图像与病史自行判断。"
)

# 强动作（"要东西"的动作，不含"请结合/请参考"这类建议型措辞）
_STRONG_ASKS = (
    "请提供",
    "请描述",
    "请上传",
    "请补充",
    "请复述",
    "麻烦提供",
    "麻烦描述",
    "需要您提供",
    "请重新提供",
)

# 对象：影像 / 图像 / 病灶等**应由系统提供**的输入
_OBJECTS = (
    "影像",
    "图像",
    "图片",
    "原图",
    "切面",
    "声像",
    "超声图",
    "DICOM",
    "dicom",
    "病灶边界",
    "边界信息",
    "边界线",
    "具体位置",
    "图像特征",
    "影像特征",
    "影像数据",
)

# 动作后 14 字内出现对象即判为索要（模型常写「请提供该结节的边界信息」）
_WINDOW = 14

_ASK_RE = re.compile("|".join(map(re.escape, _STRONG_ASKS)))
_OBJECT_RE = re.compile("|".join(map(re.escape, _OBJECTS)))


def is_system_handoff_text(text: str) -> bool:
    """是否本系统自己生成的转人工文案（兜底豁免）。"""
    return HANDOFF_MARKER in (text or "")


def detect_solicitation(text: str) -> str | None:
    """检出反向索要；命中返回片段（≤24 字，供 trace/日志留痕），否则 ``None``。"""
    if not text:
        return None
    for match in _ASK_RE.finditer(text):
        tail = text[match.start() : match.start() + _WINDOW + len(match.group(0))]
        if _OBJECT_RE.search(tail):
            end = min(len(text), match.start() + 24)
            return text[match.start() : end].replace("\n", " ")
    return None
