"""P0-4 锁文件守卫：requirements.lock 必须覆盖 requirements.txt 的全部直接依赖。

背景（15 号计划 P0-4 完成判据）：真机曾出现 prometheus_client 锁定 0.20 vs
实装 0.25 的漂移。本守卫确保：
1. requirements.lock 存在且由 uv 生成（含 autogen 标记）；
2. requirements.txt 声明的每个直接依赖都以 `pkg==<版本>` 出现在 lock 中
   （requirements.txt 的历史 loose 约束 `>=` 属既有债务，lock 以解析结果
   钉定——重跑 uv pip compile 即再生）。
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
REQ = ROOT / "requirements.txt"
LOCK = ROOT / "requirements.lock"


def _parse_pinned(path: Path) -> dict[str, str]:
    pinned: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#")[0].strip()
        if not line or line.startswith("-"):
            continue
        m = re.match(r"^([A-Za-z0-9._-]+)\s*==\s*([A-Za-z0-9.!+]+)$", line)
        if not m:
            continue
        pinned[m.group(1).lower().replace("_", "-")] = m.group(2)
    return pinned


def _direct_dep_names() -> set[str]:
    names: set[str] = set()
    for raw in REQ.read_text(encoding="utf-8").splitlines():
        line = raw.split("#")[0].strip()
        if not line or line.startswith("-"):
            continue
        m = re.match(r"^([A-Za-z0-9._-]+)", line)
        if m:
            names.add(m.group(1).lower().replace("_", "-"))
    return names


def test_lockfile_exists_and_autogenerated():
    assert LOCK.exists(), "requirements.lock 缺失（uv pip compile requirements.txt -o requirements.lock）"
    head = LOCK.read_text(encoding="utf-8")[:200]
    assert "autogenerated by uv" in head, "lock 文件不是 uv 生成的（无法追溯来源）"


def test_lockfile_covers_all_direct_deps():
    direct = _direct_dep_names()
    assert direct, "requirements.txt 解析为空"
    lock_pinned = _parse_pinned(LOCK)
    missing = sorted(direct - set(lock_pinned))
    assert missing == [], (
        "以下直接依赖未在 requirements.lock 中锁定"
        "（重跑 uv pip compile requirements.txt -o requirements.lock）: "
        f"{missing}"
    )
